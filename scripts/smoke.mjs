import { _electron as electron } from '@playwright/test';
import { mkdir, writeFile, unlink } from 'node:fs/promises';
import { resolve } from 'node:path';
import assert from 'node:assert/strict';
import { build } from 'esbuild';
import { createImportFixtures } from './fixtures.mjs';
await build({ entryPoints: ['tests/gpu-harness.ts'], bundle: true, format: 'esm', platform: 'browser', outfile: 'dist/test-harness.js' });
const data = resolve('.local-test', `profile-${Date.now()}`);
await mkdir('test-results', { recursive: true });
const env = { ...process.env, ROOMSHIFT_TEST_DATA: data, ROOMSHIFT_FAKE_CAMERA: '1' };
delete env.ELECTRON_RUN_AS_NODE;
const app = await electron.launch({ args: ['.'], env });
const errors = [];
try {
  const page = await app.firstWindow();
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', m => { if (m.type() === 'error' && !m.text().startsWith('INFO: Created TensorFlow Lite XNNPACK delegate')) errors.push(m.text()); });
  await page.getByRole('heading', { name: 'Room studio' }).waitFor();
  await page.getByText('LIVE PREVIEW', { exact: true }).waitFor({ timeout: 30000 });
  await page.getByText('Occlusion active', { exact: true }).waitFor({ timeout: 60000 });
  const pixels = await page.evaluate(async () => { const module = await import('roomshift://app/test-harness.js'); return module.checkCompositor(); });
  await writeFile('test-results/gpu.json', JSON.stringify(pixels, null, 2));
  const pngPath = resolve('.local-test', 'custom-poster.png');
  const png = await page.evaluate(() => { const canvas = document.createElement('canvas'); canvas.width = 128; canvas.height = 160; const context = canvas.getContext('2d'); context.fillStyle = '#e9e0cc'; context.fillRect(0, 0, 128, 160); context.fillStyle = '#d05b3f'; context.fillRect(24, 20, 80, 80); context.fillStyle = '#183e38'; context.font = '12px sans-serif'; context.fillText('LOCAL ART', 30, 135); return canvas.toDataURL('image/png').split(',')[1]; });
  await writeFile(pngPath, Buffer.from(png, 'base64'));
  await app.evaluate(({ dialog }, path) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [path] }); }, pngPath);
  await page.getByRole('button', { name: /Add poster Your art/ }).click();
  await page.getByText('Click corner 1 of 4, following the perimeter.', { exact: true }).waitFor();
  const stage = page.getByTestId('stage');
  const box = await stage.boundingBox();
  for (const [x, y] of [[.18, .18], [.47, .23], [.44, .69], [.16, .62]]) await page.mouse.click(box.x + box.width * x, box.y + box.height * y);
  await page.getByLabel('Object name', { exact: true }).waitFor();
  assert.equal(await page.locator('.layer').count(), 1);
  await page.getByRole('button', { name: 'Desk plant', exact: true }).click();
  assert.equal(await page.locator('.layer').count(), 2);
  await page.getByLabel('position X', { exact: true }).fill('0.5');
  await page.getByLabel('position X', { exact: true }).blur();
  // Find the actual red X-axis pixels and drag them, exercising Drei's mirrored raycasts.
  const axis = await page.evaluate(async () => {
    await new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)));
    const source = document.querySelector('.model-stage canvas');
    const scratch = document.createElement('canvas'); scratch.width = source.width; scratch.height = source.height;
    const ctx = scratch.getContext('2d'); ctx.drawImage(source, 0, 0);
    const pixels = ctx.getImageData(0, 0, scratch.width, scratch.height).data;
    let sx = 0, sy = 0, count = 0;
    for (let y = 0; y < scratch.height; y++) for (let x = 0; x < scratch.width; x++) { const i = (y * scratch.width + x) * 4; if (pixels[i] > 200 && pixels[i + 1] < 70 && pixels[i + 2] < 70 && pixels[i + 3] > 100) { sx += x; sy += y; count++; } }
    if (!count) throw new Error('No X-axis gizmo pixels');
    const rect = source.getBoundingClientRect(); return { x: rect.x + sx / count / scratch.width * rect.width, y: rect.y + sy / count / scratch.height * rect.height };
  });
  await page.mouse.move(axis.x, axis.y); await page.mouse.down(); await page.mouse.move(axis.x - 35, axis.y, { steps: 8 }); await page.mouse.up();
  const draggedX = +(await page.getByLabel('position X', { exact: true }).inputValue());
  assert.notEqual(draggedX, .5, 'Interactive gizmo did not update the model position');
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  assert.equal(+(await page.getByLabel('position X', { exact: true }).inputValue()), .5);
  await page.screenshot({ path: 'test-results/model-controls.png' });
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await page.getByText(/saved on this device/).waitFor();
  const stored = await page.evaluate(async () => {
    const listed = await window.roomshift.listScenes();
    return await window.roomshift.loadScene(listed.scenes[0].id);
  });
  assert.equal(stored.scene.objects.length, 2); assert.equal(stored.scene.objects[1].position[0], .5);
  assert.match(stored.scene.objects[0].asset, /^[a-f0-9]{64}\.png$/);
  await unlink(pngPath);
  assert.equal((await page.evaluate(async id => window.roomshift.loadScene(id), stored.scene.id)).missing.length, 0);
  const fixture = await createImportFixtures(resolve('.local-test', 'imports'));
  await app.evaluate(({ dialog }, model) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [model] }); }, fixture.model);
  await page.getByRole('button', { name: /3D model Import/ }).click();
  await page.getByLabel('Object name', { exact: true }).waitFor();
  await page.waitForFunction(() => document.querySelector('.object-name')?.value === 'Imported pyramid');
  await page.getByLabel('position X', { exact: true }).fill('-0.6');
  assert.equal(await page.locator('.layer').count(), 3);
  await page.getByRole('button', { name: 'Coastal escape WINDOW' }).click();
  for (const [x, y] of [[.58, .14], [.87, .19], [.86, .6], [.6, .63]]) await page.mouse.click(box.x + box.width * x, box.y + box.height * y);
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await page.waitForFunction(() => !document.querySelector('.statusbar')?.textContent.includes('0 fps'));
  await page.getByRole('button', { name: 'Dismiss notification' }).click();
  await page.screenshot({ path: 'test-results/editor.png' });
  await page.getByRole('button', { name: 'Go live' }).click();
  const nextWindow = app.waitForEvent('window');
  await page.getByRole('button', { name: 'Open output window' }).click();
  const output = await nextWindow;
  output.on('pageerror', e => errors.push(e.message));
  await output.waitForFunction(() => { const video = document.querySelector('video'); return video?.readyState >= 2 && video.videoWidth === 1280; }, { timeout: 30000 });
  await page.getByText('Output live', { exact: true }).waitFor();
  assert.equal(await output.locator('button').count(), 0);
  await output.screenshot({ path: 'test-results/output.png' });
  await page.getByRole('button', { name: 'Close dialog' }).click();
  await page.getByRole('button', { name: 'Preview', exact: true }).click();
  assert.equal(await page.locator('.calibration').count(), 0);
  await page.reload();
  await page.getByText('LIVE PREVIEW', { exact: true }).waitFor({ timeout: 30000 });
  assert.equal(await page.locator('.layer').count(), 4);
  const security = await page.evaluate(async () => ({ node: typeof window.require, invalidRejected: await window.roomshift.loadScene('../../outside').then(() => false, () => true) }));
  assert.equal(security.node, 'undefined'); assert.equal(security.invalidRejected, true);
  await page.addInitScript(() => {
    window.__denyCamera = true;
    const original = navigator.mediaDevices.getUserMedia.bind(navigator.mediaDevices);
    navigator.mediaDevices.getUserMedia = async constraints => {
      if (window.__denyCamera) throw new DOMException('Test denial', 'NotAllowedError');
      return original(constraints);
    };
  });
  await page.reload();
  await page.getByText(/Camera access denied/).waitFor();
  await page.evaluate(() => { window.__denyCamera = false; });
  await page.getByRole('button', { name: 'Retry camera' }).click();
  await page.getByText('LIVE PREVIEW', { exact: true }).waitFor();
  if (errors.length) throw new Error(`Renderer errors: ${errors.join('\n')}`);
  await writeFile('test-results/smoke.json', JSON.stringify({ passed: true, syntheticCamera: true, checks: ['camera startup', 'MediaPipe inference', 'GPU homography and foreground blending', 'native PNG import (dialog stub)', 'managed asset survives source deletion', 'four-corner poster', '3D demo transform', 'mirrored 3D gizmo pointer drag and undo', 'self-contained GLB import', 'window calibration', 'IPC scene save/load', 'reload restores scene', 'clean output WebRTC', 'preview hides controls', 'IPC path validation', 'camera denial and retry (mocked)'], consoleErrors: errors }, null, 2));
  console.log('Electron synthetic-camera integration checks passed.');
} catch (error) {
  console.error('Renderer diagnostics:', errors);
  const windows = app.windows();
  if (windows[0]) await windows[0].screenshot({ path: 'test-results/failure.png' }).catch(() => {});
  throw error;
} finally { await app.close(); await unlink('dist/test-harness.js').catch(() => {}); }
